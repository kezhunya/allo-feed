def load_allo_existing_categories(allo_categories: dict[str, dict]) -> list[AlloExistingCategory]:
    wb = load_workbook(ALLO_EXISTING_CATEGORIES_XLSX, read_only=True, data_only=True)
    ws = wb[wb.sheetnames[0]]
    scraped_items = [(url, meta["title"]) for url, meta in allo_categories.items()]
    scraped_title_to_url = {meta["title"]: url for url, meta in allo_categories.items()}
    result: list[AlloExistingCategory] = []
    for row in ws.iter_rows(min_row=2, values_only=True):
        code, title = row[:2]
        title = normalize_text(str(title))
        if not title:
            continue
        alias_title = EXISTING_TO_SCRAPED_CATEGORY_ALIASES.get(title, "")
        best_url = scraped_title_to_url.get(alias_title, "")
        best_scraped_title = alias_title if best_url else ""
        best_score = 1.0 if best_url else 0.0
        if not best_url:
            for url, scraped_title in scraped_items:
                score = similarity(title, scraped_title)
                if score > best_score:
                    best_score = score
                    best_url = url
                    best_scraped_title = scraped_title
            if best_score < 0.58:
                best_url = ""
                best_scraped_title = ""
        result.append(
            AlloExistingCategory(
                code=str(code).strip(),
                title=title,
                mapped_url=best_url,
                mapped_scraped_title=best_scraped_title,
            )
        )
    return result


