def add_header(ws, headers: list[str]) -> None:
    ws.append(headers)
    for cell in ws[1]:
        cell.fill = HEADER_FILL
        cell.font = Font(bold=True)
        cell.border = copy(GRID_BORDER)


def row_fill_for_status(status: str) -> PatternFill:
    if status in {"Точно сопоставлено", "Сверено автоматически"}:
        return GREEN_FILL
    if status == "Нужно проверить":
        return YELLOW_FILL
    return RED_FILL


def apply_fill(row_cells, fill: PatternFill) -> None:
    for cell in row_cells:
        cell.fill = fill


def apply_default_border(row_cells) -> None:
    for cell in row_cells:
        border = cell.border
        sides = [
            getattr(border, "left", None),
            getattr(border, "right", None),
            getattr(border, "top", None),
            getattr(border, "bottom", None),
        ]
        if not any(side and side.style for side in sides):
            cell.border = copy(GRID_BORDER)


def category_status(manual_url: str | None, suggested_title: str) -> str:
    if manual_url and suggested_title:
        return "Точно сопоставлено"
    if suggested_title:
        return "Нужно проверить"
    return "Требует заполнения"


def param_status(source_param_name: str, target_url: str, suggested_filter: str) -> str:
    if not suggested_filter:
        return "Требует заполнения"
    global_override = GLOBAL_PARAM_SUGGESTIONS.get(normalize_key(source_param_name), "")
    if global_override == suggested_filter:
        return "Точно сопоставлено"
    overrides = ALLO_PARAM_SUGGESTIONS_BY_URL.get(target_url, {})
    override_value = overrides.get(normalize_key(source_param_name), "")
    if override_value == suggested_filter:
        return "Точно сопоставлено"
    alias = COMMON_PARAM_NAME_MAP.get(normalize_key(source_param_name), "")
    if alias and normalize_key(alias) == normalize_key(suggested_filter):
        return "Точно сопоставлено"
    if normalize_key(source_param_name) == normalize_key(suggested_filter):
        return "Точно сопоставлено"
    return "Нужно проверить"


def make_multiline(values: list[str]) -> str:
    cleaned = [normalize_text(v) for v in values if normalize_text(v)]
    return "\n".join(cleaned)


