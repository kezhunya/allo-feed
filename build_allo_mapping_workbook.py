def suggest_kitchen_sink_rule_value(
    filter_name: str,
    source_value: str,
    allowed_values: list[str],
) -> str:
    source_key = normalize_key(source_value)
    if filter_name == "Материал":
        for needle, target in KITCHEN_SINK_MATERIAL_RULES.items():
            if needle in source_key:
                return pick_allowed_preferred(target, allowed_values)
    if filter_name == "Тип установки":
        matched_targets = [
            target
            for needle, target in KITCHEN_SINK_MOUNT_RULES.items()
            if needle in source_key
        ]
        if len(set(matched_targets)) > 1 and "Универсальный" in allowed_values:
            return "Универсальный"
        if matched_targets:
            return pick_allowed_preferred(matched_targets[0], allowed_values)
    if filter_name == "Количество чаш мойки":
        compact = normalize_text(source_value).lower().replace(" ", "").replace(".", ",")
        if compact.startswith("1,5") or source_key.startswith("1 5"):
            return pick_allowed_preferred("1 основная / 1 дополнительная", allowed_values)
        if compact.startswith("2"):
            return pick_allowed_preferred("2 основных", allowed_values)
        if compact.startswith("1"):
            return pick_allowed_preferred("1 основная", allowed_values)
    if filter_name == "Наличие крыла":
        return pick_allowed_preferred("Есть" if "с крылом" in source_key else "Нет", allowed_values)
    if filter_name == "Форма":
        for needle, target in KITCHEN_SINK_SHAPE_RULES.items():
            if needle in source_key:
                return pick_allowed_preferred(target, allowed_values)
    if filter_name in {"Ширина мойки, мм", "Глубина мойки, мм", "Высота мойки, мм"}:
        value_text = normalize_text(source_value).lower()
        if any(marker in value_text for marker in ("-", "–", "—", "менее", "более", "до", "свыше")):
            return ""
        number = extract_float(source_value)
        if number is None:
            return ""
        mm = number * 10
        if mm.is_integer():
            return str(int(mm))
        return str(mm).rstrip("0").rstrip(".")
    return ""


def suggest_manual_value_rule(
    target_category_name: str,
    filter_name: str,
    source_param_name: str,
    source_value: str,
    allowed_values: list[str],
) -> str:
    target_category_key = normalize_key(target_category_name)
    filter_key = normalize_key(filter_name)
    source_value_key = normalize_key(source_value)
    target = MANUAL_VALUE_RULES.get(
        (
            target_category_key,
            normalize_key(source_param_name),
            filter_key,
            source_value_key,
        ),
        "",
    )
    if not target:
        fallback_targets = {
            value
            for (rule_category, _rule_param, rule_filter, rule_value), value in MANUAL_VALUE_RULES.items()
            if rule_category == target_category_key
            and rule_filter == filter_key
            and rule_value == source_value_key
        }
        if len(fallback_targets) == 1:
            target = next(iter(fallback_targets))
    if not target:
        return ""
    return pick_allowed_preferred(target, allowed_values) or target


def extract_float(value: str | None) -> float | None:
    text = normalize_text(value).replace(",", ".")
    match = re.search(r"-?\d+(?:\.\d+)?", text)
    if not match:
        return None
    try:
        return float(match.group(0))
    except ValueError:
        return None


def parse_size_pair(value: str | None) -> tuple[str, str] | None:
    text = normalize_text(value).lower().replace("х", "x")
    match = re.search(r"(\d+(?:[.,]\d+)?)\s*x\s*(\d+(?:[.,]\d+)?)", text)
    if not match:
        return None
    first = match.group(1).replace(",", ".")
    second = match.group(2).replace(",", ".")
    return first, second


def parse_allowed_numeric_range(value: str) -> tuple[float | None, float | None] | None:
    text = normalize_text(value).replace(",", ".")
    numbers = [float(n) for n in re.findall(r"\d+(?:\.\d+)?", text)]
    lower_text = text.lower()
    if not numbers:
        return None
    if ("до" in lower_text or "менее" in lower_text) and len(numbers) >= 1:
        return (None, numbers[0])
    if ("более" in lower_text or "и более" in lower_text or "свыше" in lower_text) and len(numbers) >= 1:
        return (numbers[0], None)
    if len(numbers) >= 2:
        return (numbers[0], numbers[1])
    if len(numbers) == 1 and re.fullmatch(r"\d+(?:\.\d+)?(?:\s*[^\d\s]+.*)?", text):
        return (numbers[0], numbers[0])
    return None


def parse_warranty_months(value: str | None) -> int | None:
    text = normalize_text(value).replace(",", ".")
    key = normalize_key(text)
    number = extract_float(text)
    if number is None:
        return None
    if any(marker in key for marker in ("год", "года", "лет", "рік", "роки", "років")):
        return int(round(number * 12))
    return int(round(number))


def suggest_warranty_value(source_value: str, allowed_values: list[str]) -> str:
    source_months = parse_warranty_months(source_value)
    if source_months is None:
        return ""
    for allowed in allowed_values:
        allowed_months = parse_warranty_months(allowed)
        if allowed_months == source_months:
            return allowed
    return ""


def match_allowed_range(source_value: str, allowed_values: list[str], source_param_name: str) -> str:
    raw_number = extract_float(source_value)
    if raw_number is None:
        return ""
    number = raw_number
    source_key = normalize_key(source_param_name)
    allowed_joined = " ".join(allowed_values).lower()
    if "л мин" in source_key and "л/час" in allowed_joined:
        number *= 60
    if "мм" in source_key and " см" in allowed_joined:
        number /= 10
    if "см" in source_key and "мм" in allowed_joined:
        number *= 10

    for allowed in allowed_values:
        parsed = parse_allowed_numeric_range(allowed)
        if not parsed:
            continue
        low, high = parsed
        if low is not None and number < low:
            continue
        if high is not None and number > high:
            continue
        return allowed
    return ""


def match_exact_dimension_value(source_value: str, allowed_values: list[str], scale: float = 1.0) -> str:
    number = extract_float(source_value)
    if number is None:
        return ""
    number *= scale
    scored: list[tuple[float, str]] = []
    for allowed in allowed_values:
        allowed_number = extract_float(allowed)
        if allowed_number is None:
            continue
        scored.append((abs(allowed_number - number), allowed))
    if not scored:
        return ""
    scored.sort(key=lambda item: (item[0], item[1]))
    if scored[0][0] <= 1.0:
        return scored[0][1]
    return ""


def suggest_thread_connection_value(source_value: str, allowed_values: list[str]) -> str:
    source_key = normalize_key(source_value)
    if not source_key:
        return ""

    cleaned = source_key
    for noise in (
        "с разборным соединением",
        "разборное соединение",
        "разборное соеденение",
        "проходная",
    ):
        cleaned = cleaned.replace(normalize_key(noise), " ")
    cleaned = re.sub(r"\s+", " ", cleaned).strip()

    has_outer = "наружн" in cleaned
    has_inner = "внутрен" in cleaned
    has_solder = "пайк" in cleaned
    has_press = any(token in cleaned for token in ("обжим", "цанг", "натяж", "аксиаль", "евроконус"))

    candidates: list[str] = []

    if has_solder:
        if has_outer:
            candidates.append("Пайка-наружное")
        if has_inner:
            candidates.append("Пайка-внутреннее")
        if not has_outer and not has_inner:
            candidates.append("Пайка-пайка")
    elif has_press:
        if has_outer and "Обжим-наружное" in allowed_values:
            candidates.append("Обжим-наружное")
        if has_inner and "Обжим-внутреннее-обжим" in allowed_values:
            candidates.append("Обжим-внутреннее-обжим")
        if has_outer and has_inner and "Обжим-наружное-обжим" in allowed_values:
            candidates.append("Обжим-наружное-обжим")
    else:
        if has_outer and has_inner:
            candidates.append("Наружное-внутреннее")
            candidates.append("Наружное-внутреннее-наружное")
        elif has_outer:
            candidates.append("Наружная")
            candidates.append("Наружное-наружное")
        elif has_inner:
            candidates.append("Внутренняя")

    for candidate in candidates:
        if candidate in allowed_values:
            return candidate
    return ""


