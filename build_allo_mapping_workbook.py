            display_name = raw_header.replace("*", "").strip()
            base_key = normalize_key(display_name)
            if base_key in template_skip_keys:
                continue
            dv = dv_by_col.get(col)
            values = parse_template_validation_values(wb, getattr(dv, "formula1", None))
            if not values and example_ws is not None:
                example_col = example_col_by_code.get(code) or example_col_by_header.get(display_name)
                if example_col:
                    example_type = normalize_text(example_ws.cell(2, example_col).value) or field_type
