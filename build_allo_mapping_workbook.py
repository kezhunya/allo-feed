def strip_selector_conditions(value: str | None) -> str:
    text = normalize_text(value)
    if not text:
        return ""
    text = text.split("+", 1)[0].strip()
    text = text.split("(", 1)[0].strip()
    if "/" in text:
        text = text.split("/")[-1].strip()
    return normalize_text(text)


def split_rule_assignments(value: str | None) -> list[tuple[str, str]]:
    text = normalize_text(value)
    if not text:
        return []
    chunks: list[str] = []
    for part in text.split(";"):
        chunks.extend(re.split(r"\s+и\s+(?=[^=]{1,40}=)", part))
    result: list[tuple[str, str]] = []
    for chunk in chunks:
        if "=" not in chunk:
            continue
        name, val = chunk.split("=", 1)
        name = canonical_filter_name(name)
        val = canonical_value_name(val)
        if name and val:
            result.append((name, val))
    return result


def load_section_fixed_rules() -> list[SectionFixedRule]:
    rules: list[SectionFixedRule] = []
    if not ALLO_SECTION_RULES_XLSX.exists():
        return rules
    wb = load_workbook(ALLO_SECTION_RULES_XLSX, data_only=True)
    for ws in wb.worksheets:
        in_section_block = False
        for row in ws.iter_rows(values_only=True):
            cells = [normalize_text(value) for value in row]
            row_texts = [value for value in cells if value]
            if not row_texts:
                continue
            first = cells[0] if len(cells) > 0 else ""
            second = cells[1] if len(cells) > 1 else ""
            fourth = cells[3] if len(cells) > 3 else ""
            if any(normalize_key(value) == "наш раздел" for value in row_texts):
                in_section_block = True
                continue
            if not in_section_block:
                continue
            selector = second
            rule_text = fourth
            if not selector and len(row_texts) >= 1:
                selector = row_texts[0]
            if not rule_text and len(row_texts) >= 2:
                rule_text = row_texts[-1]
            if not selector and not rule_text:
                continue
            if any(normalize_key(value) == "все остальное выше уже перечислено" for value in row_texts):
                break
            if first and not str(first).isdigit():
                break
            # Эта загрузка используется только для простых правил уровня раздела.
            # Условные строки вида "Раздел+Параметр=Значение" оставляем для будущего
            # ALLO feed generator и не пытаемся грубо расплющивать здесь.
            if "+" in selector or "=" in selector:
                continue
            selector = strip_selector_conditions(selector)
            if not selector:
                continue
            low = rule_text.lower()
            skip_feed = "не добавляем в фид" in low
            assignments = [] if skip_feed else split_rule_assignments(rule_text)
            if skip_feed or assignments:
                rules.append(
                    SectionFixedRule(
                        selector=selector,
                        assignments=assignments,
                        skip_feed=skip_feed,
                    )
                )
    return rules


def source_category_matches_rule(category_name: str, selector: str) -> bool:
    source_key = normalize_key(category_name)
    selector_key = normalize_key(selector)
    if not source_key or not selector_key:
        return False
    if source_key == selector_key:
        return True
    if selector_key in source_key or source_key in selector_key:
        return True
    return False


def canonical_filter_name(value: str | None) -> str:
    name = normalize_text(value)
    return FILTER_DISPLAY_ALIASES.get(name, name)


def canonical_value_name(value: str | None) -> str:
    name = normalize_text(value)
    return VALUE_DISPLAY_ALIASES.get(name, name)


def canonical_allo_url(value: str | None) -> str:
    url = normalize_text(value)
    return url.replace("/ua/", "/ru/")


def split_allo_path(url: str) -> list[str]:
    path = re.sub(r"^https?://[^/]+", "", url).strip("/")
    parts = path.split("/")
    if parts and parts[0] in {"ru", "ua"}:
        parts = parts[1:]
    return [part for part in parts if part]


def is_base_allo_category_url(url: str) -> bool:
    parts = split_allo_path(url)
    if len(parts) == 1:
        return True
    if len(parts) == 2 and parts[0] == "products":
        return True
    return False


def tokenize(value: str | None) -> set[str]:
    stop = {"для", "и", "в", "на", "к", "из", "по", "до", "с", "со", "комнаты", "комната"}
    return {t for t in normalize_key(value).split() if t and t not in stop}


def similarity(a: str, b: str) -> float:
    ak = normalize_key(a)
    bk = normalize_key(b)
    if not ak or not bk:
        return 0.0
    ratio = SequenceMatcher(None, ak, bk).ratio()
    ta = tokenize(a)
    tb = tokenize(b)
    overlap = len(ta & tb) / max(len(ta | tb), 1)
    bonus = 0.0
    if ak in bk or bk in ak:
        bonus += 0.35
    return ratio * 0.7 + overlap * 0.9 + bonus


